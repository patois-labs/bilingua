"""Writes src/decdiff.rs: where Python's codecs (what LocOS reads with) and encoding_rs disagree about a byte sequence,
for the ANSI codecs an HTML Help file may be read with, plus the EUC-KR (KS X 1001 Annex 3) make-up tables.

    cargo run -p bilingua-htmlhelp --example htmlhelp_decraw -- DECRAW.txt
    C:\\Users\\brent\\code\\local-tms\\.venv\\Scripts\\python.exe -I gen_decdiff.py DECRAW.txt ../../src/decdiff.rs

The Rust decoder (src/enc.rs) reads a byte >= 0x80 as the one character its single byte is, else the one character
of the pair it starts, else (EUC-JP 8F, GB18030) the triple or four-byte sequence; "is" means Python's codec gives
exactly that one character for exactly those bytes. An entry here overrides encoding_rs for one sequence (0xFFFFFFFF:
Python reads no single character from it). An entry with an empty sequence list cannot happen.
"""

import sys

CODECS = {874: "cp874", 932: "cp932", 936: "gbk", 949: "cp949", 950: "cp950", 1250: "cp1250", 1251: "cp1251",
          1252: "cp1252", 1253: "cp1253", 1254: "cp1254", 1255: "cp1255", 1256: "cp1256", 1257: "cp1257",
          1258: "cp1258", 3001: "shift_jis", 3002: "gb2312", 3003: "big5", 3004: "euc_kr", 3005: "iso8859_2",
          3006: "iso8859_5", 3007: "iso8859_7", 3008: "iso8859_9", 3009: "iso8859_15", 3010: "koi8_r", 3011: "koi8_u",
          3012: "euc_jp", 3013: "gb18030"}


def py_one(codec: str, seq: bytes):
    try:
        s = seq.decode(codec)
    except UnicodeDecodeError:
        return None
    return ord(s) if len(s) == 1 else None


rows = []
n = 0
with open(sys.argv[1], encoding="ascii") as fh:
    for line in fh:
        cp, hx, u = line.split()
        cp = int(cp)
        seq = bytes.fromhex(hx)
        n += 1
        mine = None if u == "-" else int(u, 16)
        if cp in (3002, 3004) and len(seq) == 2 and min(seq) < 0xA1:
            mine = None  # the Rust decoder's rule: GB2312 and KS X 1001 pairs are both bytes A1..FE (EUC)
        py = py_one(CODECS[cp], seq)
        if py != mine:
            rows.append((cp, len(seq), int(hx, 16), py))

# Every codec reads bytes below 0x80 as ASCII (the Rust decoder does not look them up).
for codec in CODECS.values():
    assert bytes(range(0x80)).decode(codec) == bytes(range(0x80)).decode("ascii"), codec

# Single-byte table check: Python's single-byte reading of every lead must agree with "single first" (a byte that is a
# character alone is never also a lead byte).
for cp, codec in CODECS.items():
    for b in range(0x80, 0x100):
        if py_one(codec, bytes([b])) is not None:
            for t in range(0x40, 0x100):
                if py_one(codec, bytes([b, t])) is not None:
                    raise SystemExit(f"{codec}: byte {b:02x} is both a character and a lead byte")

rows.sort()
out = ["// Generated by tests/tools/gen_decdiff.py; do not edit.", "",
       "/// (key, character) where Python's codec reads a byte sequence differently from encoding_rs. The key is",
       "/// `codec id << 40 | length << 32 | bytes (big-endian)`; the character 0xFFFFFFFF means Python reads no single",
       "/// character from exactly these bytes.",
       "pub static DEC_DIFF: &[(u64, u32)] = &["]
for cp, ln, val, py in rows:
    key = (cp << 40) | (ln << 32) | val
    out.append(f"    (0x{key:x}, 0x{(0xFFFFFFFF if py is None else py):x}),")
out.append("];")

# EUC-KR make-up sequences (A4 D4 A4 cho A4 jung A4 jong): Python's euc_kr reads and writes them.
cho_of = []
jong_of = []
for c in range(0xA1, 0xBF):
    s = py_one("euc_kr", bytes([0xA4, 0xD4, 0xA4, c, 0xA4, 0xBF, 0xA4, 0xD4]))
    cho_of.append(0xFF if s is None else (s - 0xAC00) // 588)
    s = py_one("euc_kr", bytes([0xA4, 0xD4, 0xA4, 0xA1, 0xA4, 0xBF, 0xA4, c]))
    jong_of.append(0xFF if s is None else (s - 0xAC00) % 28)
cho_byte = [0] * 19
jong_byte = [0] * 28
make_up = 0
for s in range(0xAC00, 0xD7A4):
    b = chr(s).encode("euc_kr")
    if len(b) == 8:
        make_up += 1
        k = s - 0xAC00
        cho_byte[k // 588] = b[3]
        jong_byte[k % 28] = b[7]
        assert b[:3] == b"\xa4\xd4\xa4" and b[4] == 0xA4 and b[5] == 0xBF + (k % 588) // 28 and b[6] == 0xA4, hex(s)
    else:
        assert len(b) == 2, hex(s)
# the decode side agrees with the encode side
for s in range(0xAC00, 0xD7A4):
    k = s - 0xAC00
    seq = bytes([0xA4, 0xD4, 0xA4, cho_byte[k // 588], 0xA4, 0xBF + (k % 588) // 28, 0xA4, jong_byte[k % 28]])
    assert py_one("euc_kr", seq) == s, hex(s)
out.append("")
out.append("/// EUC-KR make-up: the choseong index of byte 0xA1 + i (0xFF: none), as Python's euc_kr reads it.")
out.append("pub static EUCKR_CHO_OF: [u8; 30] = [" + ", ".join(str(x) for x in cho_of) + "];")
out.append("/// EUC-KR make-up: the jongseong index of byte 0xA1 + i (0xFF: none); 0xD4 (filler) is index 0.")
out.append("pub static EUCKR_JONG_OF: [u8; 30] = [" + ", ".join(str(x) for x in jong_of) + "];")
out.append("/// EUC-KR make-up: the byte Python's euc_kr writes for each choseong index.")
out.append("pub static EUCKR_CHO_BYTE: [u8; 19] = [" + ", ".join(f"0x{x:02x}" for x in cho_byte) + "];")
out.append("/// EUC-KR make-up: the byte Python's euc_kr writes for each jongseong index (0: the filler 0xD4).")
out.append("pub static EUCKR_JONG_BYTE: [u8; 28] = [" + ", ".join(f"0x{x:02x}" for x in jong_byte) + "];")
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(out) + "\n")
by = {}
for cp, *_ in rows:
    by[cp] = by.get(cp, 0) + 1
print(n, "sequences compared,", len(rows), "differences", by, ";", make_up, "euc_kr make-up syllables")
