"""Writes src/data.rs: the three tables the Rust crate cannot compute (read only use of Python's standard library
and Babel from the Localization OS venv):

  * ENTITIES: the HTML5 named character references, as html.unescape reads them.
  * LCIDS: Windows LCID, POSIX-style name, and the English display name HTML Help Workshop writes after
    "Language=0x40c " (Babel's, reduced to ASCII), for every region LCID Python knows.
  * CP1258: characters Windows-1258 cannot write directly, with the base + combining tone mark form it can.

    C:\\Users\\brent\\code\\local-tms\\.venv\\Scripts\\python.exe gen_tables.py ../../src/data.rs
"""

import html
import html.entities
import locale
import sys
import unicodedata

out = sys.argv[1]


def lit(s: str) -> str:
    return '"' + "".join(c if (c.isascii() and c.isprintable() and c not in '"\\') else "\\u{%x}" % ord(c) for c in s) + '"'


lines = ["// Generated by tests/tools/gen_tables.py; do not edit.", ""]

ents = sorted(html.entities.html5.items(), key=lambda kv: kv[0].encode())
lines.append("/// HTML5 named character references (with the trailing `;` where the name has one), sorted by name.")
lines.append("pub static ENTITIES: &[(&str, &str)] = &[")
for k, v in ents:
    lines.append(f"    ({lit(k)}, {lit(v)}),")
lines.append("];")
lines.append("")

lines.append("/// (LCID, POSIX-style name, English display name) for every Windows region LCID.")
lines.append("pub static LCIDS: &[(u32, &str, &str)] = &[")
for lcid, name in sorted(locale.windows_locale.items()):
    disp = ""
    try:
        from babel import Locale

        disp = Locale.parse(name).get_display_name("en") or ""
    except Exception:
        disp = ""
    disp = unicodedata.normalize("NFKD", disp).encode("ascii", "ignore").decode("ascii")
    lines.append(f"    ({lcid:#x}, {lit(name)}, {lit(disp)}),")
lines.append("];")
lines.append("")

# Same arithmetic as htmlhelp_filter._cp1258_text.
TONES = frozenset("\u0323\u0300\u0301\u0303\u0309")
pairs = []
for cp in range(0x80, 0x30000):
    ch = chr(cp)
    if 0xD800 <= cp <= 0xDFFF:
        continue
    try:
        ch.encode("cp1258")
        continue
    except UnicodeEncodeError:
        pass
    d = unicodedata.normalize("NFD", ch)
    marks = d[1:]
    vowel = "".join(m for m in marks if m not in TONES)
    base = unicodedata.normalize("NFC", d[0] + vowel)
    alt = base + "".join(m for m in marks if m in TONES)
    try:
        alt.encode("cp1258")
    except UnicodeEncodeError:
        continue
    pairs.append((ch, alt))
lines.append("/// (character, form Windows-1258 can write) for characters it has no single byte for.")
lines.append("pub static CP1258: &[(char, &str)] = &[")
for ch, alt in pairs:
    lines.append(f"    ('\\u{{{ord(ch):x}}}', {lit(alt)}),")
lines.append("];")

with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(len(ents), "entities,", len(pairs), "cp1258 pairs")

# Charset names a file may declare: Python's alias table, reduced to the codecs LocOS accepts (_SOURCE_OK).
import encodings.aliases  # noqa: E402

OK = {"cp1250", "cp1251", "cp1252", "cp1253", "cp1254", "cp1255", "cp1256", "cp1257", "cp1258", "cp874", "cp932", "gbk",
      "cp949", "cp950", "iso8859-1", "iso8859-2", "iso8859-5", "iso8859-7", "iso8859-9", "iso8859-15", "koi8-r", "koi8-u",
      "shift_jis", "euc_jp", "gb2312", "gb18030", "big5", "euc_kr"}
import codecs  # noqa: E402

cands = set(encodings.aliases.aliases) | {n.replace("-", "_") for n in OK}
rows = {}
for a in cands:
    try:
        n = codecs.lookup(a).name
    except LookupError:
        continue
    if n in OK:
        rows[a] = n
with open(out, "a", encoding="utf-8", newline="\n") as fh:
    fh.write("\n/// Charset label (Python-normalised) to the name of the Python codec LocOS reads and writes it with.\n")
    fh.write("pub static ALIASES: &[(&str, &str)] = &[\n")
    for a in sorted(rows, key=lambda k: k.encode()):
        fh.write(f'    ("{a}", "{rows[a]}"),\n')
    fh.write("];\n")
print(len(rows), "aliases")
