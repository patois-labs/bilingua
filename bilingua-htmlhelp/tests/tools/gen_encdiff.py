"""Writes src/encdiff.rs: where Python's codecs (what LocOS writes) and encoding_rs (what this crate uses)
disagree about the bytes of a character, for the ANSI code pages HTML Help uses.

    cargo run -p bilingua-htmlhelp --example htmlhelp_encmap -- ENCMAP.txt
    C:\\Users\\brent\\code\\local-tms\\.venv\\Scripts\\python.exe gen_encdiff.py ENCMAP.txt ../../src/encdiff.rs

An entry with no bytes means Python cannot encode the character at all (so the merge refuses it, as LocOS does).
"""

import sys

CODECS = {3001: "shift_jis", 3003: "big5", 3005: "iso8859_2", 3006: "iso8859_5",
          3007: "iso8859_7", 3008: "iso8859_9", 3009: "iso8859_15", 3010: "koi8_r", 3011: "koi8_u", 
          3013: "gb18030", 874: "cp874", 932: "cp932", 936: "gbk", 949: "cp949", 950: "cp950", 1250: "cp1250", 1251: "cp1251",
          1252: "cp1252", 1253: "cp1253", 1254: "cp1254", 1255: "cp1255", 1256: "cp1256", 1257: "cp1257", 1258: "cp1258"}

SKIP = {3002, 3004, 3012}  # gb2312, euc_kr, euc_jp: Python's are subsets of encoding_rs's and the diff would be 30,000 entries
rows = []
n = 0
with open(sys.argv[1], encoding="ascii") as fh:
    for line in fh:
        cp, u, hx = line.split()
        cp, u = int(cp), int(u, 16)
        if cp in SKIP:
            continue
        n += 1
        try:
            py = chr(u).encode(CODECS[cp]).hex()
        except UnicodeEncodeError:
            py = ""
        mine = "" if hx == "-" else hx
        if py != mine:
            rows.append((cp, u, py))
rows.sort()
lines = ["// Generated by tests/tools/gen_encdiff.py; do not edit.", "",
         "/// (code page, character, bytes Python's codec writes; empty when it cannot) where encoding_rs differs.",
         "pub static ENC_DIFF: &[(u16, u32, &[u8])] = &["]
for cp, u, py in rows:
    b = ", ".join("0x" + py[i : i + 2] for i in range(0, len(py), 2))
    lines.append(f"    ({cp}, 0x{u:x}, &[{b}]),")
lines.append("];")
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
by = {}
for cp, _, _ in rows:
    by[cp] = by.get(cp, 0) + 1
print(n, "chars compared,", len(rows), "differences", by)

# Python's gb2312 is a strict subset of encoding_rs's GBK with the same bytes: only the set of characters it can write.
ok = []
for u in range(0x80, 0x10000):
    if 0xD800 <= u <= 0xDFFF:
        continue
    try:
        chr(u).encode("gb2312")
        ok.append(u)
    except UnicodeEncodeError:
        pass
with open(sys.argv[2], "a", encoding="utf-8", newline="\n") as fh:
    fh.write("\n/// Non-ASCII BMP characters Python's gb2312 codec writes (the id 3002 codec writes nothing else).\n")
    fh.write("pub static GB2312_OK: &[u16] = &[\n")
    for i in range(0, len(ok), 12):
        fh.write("    " + ", ".join(f"0x{u:04x}" for u in ok[i : i + 12]) + ",\n")
    fh.write("];\n")
print(len(ok), "gb2312 characters")
