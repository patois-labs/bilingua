"""Writes src/entities.rs: Python's html.unescape tables (html.entities.html5 and the invalid character
reference tables), so the Rust unescape is the same function.

    python -I gen_entities.py OUT.rs
"""
import html
import html.entities as e
import sys

out = sys.argv[1]
items = sorted(e.html5.items())


def lit(s):
    return "".join("\\u{%x}" % ord(c) for c in s)


lines = ["// Generated by tests/tools/gen_entities.py from Python's html.entities.html5. Do not edit.", ""]
lines.append("pub(crate) static HTML5: &[(&str, &str)] = &[")
for k, v in items:
    lines.append('    ("%s", "%s"),' % (k, lit(v)))
lines.append("];")
lines.append("")
lines.append("/// (code point, replacement) of html._invalid_charrefs.")
lines.append("pub(crate) static INVALID_CHARREFS: &[(u32, &str)] = &[")
for k, v in sorted(html._invalid_charrefs.items()):
    lines.append('    (0x%x, "%s"),' % (k, lit(v)))
lines.append("];")
lines.append("")
lines.append("/// html._invalid_codepoints, sorted.")
lines.append("pub(crate) static INVALID_CODEPOINTS: &[u32] = &[")
cps = sorted(html._invalid_codepoints)
for i in range(0, len(cps), 12):
    lines.append("    " + ", ".join("0x%x" % c for c in cps[i : i + 12]) + ",")
lines.append("];")
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(len(items), "entities")
