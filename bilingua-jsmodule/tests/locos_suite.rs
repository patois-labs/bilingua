// 5 test_translated_round_trip
#[test]
fn translated_round_trip_splices_only_changed_literals() {
    let out = build_str(
        ESM,
        &[
            (0, "Startseite"),
            (2, "Hallo, \u{27E6}p1\u{27E7}!"),
            (6, "Erste"),
        ],
    );
    assert!(out.contains("home: 'Startseite',"), "{out}");
    assert!(out.contains("greeting: 'Hallo, {name}!',"));
    assert!(out.contains("list: ['Erste', 'Second', '---'],"));
    assert_eq!(
        out.replace("Startseite", "Home")
            .replace("Hallo", "Hello")
            .replace("Erste", "First"),
        ESM
    );
    let crlf = ESM.replace('\n', "\r\n");
    let out2 = build_str(&crlf, &[(1, "\u{dc}ber uns")]);
    assert!(out2.contains("about: \"\u{dc}ber uns\",\r\n"), "{out2}");
    assert_eq!(out2.matches("\r\n").count(), ESM.matches('\n').count());
    let mut bom = vec![0xEF, 0xBB, 0xBF];
    bom.extend_from_slice(ESM.as_bytes());
    assert!(build(&bom, &[(0, "Start")]).starts_with(b"\xef\xbb\xbf// Generated"));
    let out3 = build_str(
        TS,
        &[(2, "Mehrzeiliger\nTitel"), (3, "\u{27E6}x1\u{27E7}Keine\u{27E6}x2\u{27E7}\u{27E6}x3\u{27E7} Ding\u{27E6}x4\u{27E7}\u{27E6}x5\u{27E7} Dinge\u{27E6}x6\u{27E7}")],
    );
    assert!(out3.contains("title: `Mehrzeiliger\nTitel`,"), "{out3}");
    assert!(out3.contains("items: '{count, plural, =0 {Keine} one {# Ding} other {# Dinge}}',"));
    let out4 = build_str(TS, &[(5, "Teil eins und zwei")]);
    assert!(out4.contains("concat: 'Teil eins und zwei',"), "{out4}");
    assert_eq!(texts_str(&out3)[2], "Mehrzeiliger\nTitel");
}

// 6 test_escapes_per_quote
#[test]
fn escapes_decoded_per_ecmascript_and_reescaped_per_quote() {
    let src = "export default { a: 'A', b: \"B\", c: `C`, d: 'D' }";
    let nasty = "It's \"quoted\" \\ back ${x} `tick`\nnew\ttab \u{2028}";
    let mut doc = extract_str(src).unwrap();
    for id in ["u1", "u2", "u3"] {
        doc.set_target(id, vec![Inline::text(nasty)]).unwrap();
    }
    let out = String::from_utf8(JsModule.merge(&doc).unwrap()).unwrap();
    assert!(
        out.contains(r#"a: 'It\'s "quoted" \\ back ${x} `tick`\nnew\ttab \u2028'"#),
        "{out}"
    );
    assert!(
        out.contains(r#"b: "It's \"quoted\" \\ back ${x} `tick`\nnew\ttab \u2028""#),
        "{out}"
    );
    assert!(
        out.contains(r#"c: `It's "quoted" \\ back \${x} \`tick\`\nnew\ttab \u2028`"#),
        "{out}"
    );
    // the rebuilt file reads back to exactly the translated values
    let recs = records(out.as_bytes()).unwrap();
    assert_eq!(
        recs.iter()
            .take(3)
            .map(|r| r.value.as_str())
            .collect::<Vec<_>>(),
        [nasty; 3]
    );
    let dec = "export default { e: 'It\\'s \\x41\u{e9}\\u{1F600}\u{1F600} a\\\nb \\0 end', f: `t\\`ick` }";
    assert_eq!(
        texts_str(dec),
        ["It's A\u{e9}\u{1F600}\u{1F600} ab \0 end", "t`ick"]
    );
}

// 7 test_placeholders_and_unknown_tokens
#[test]
fn placeholders_protected_unknown_tokens_dropped_placeholder_only_skipped() {
    let src = "export default { a: 'Hi {{name}}, %s and {count} <b>bold</b>' }";
    assert_eq!(texts_str(src), ["Hi \u{27E6}p1\u{27E7}, \u{27E6}x2\u{27E7} and \u{27E6}p3\u{27E7} \u{27E6}x4\u{27E7}bold\u{27E6}x5\u{27E7}"]);
    // a dropped token is dropped; an invented token is not written into the file
    let out = build_str(
        src,
        &[(
            0,
            "Hallo \u{27E6}x1\u{27E7} \u{27E6}x9\u{27E7} \u{27E6}g1\u{27E7}fett\u{27E6}/g1\u{27E7}",
        )],
    );
    assert!(out.contains("a: 'Hallo {{name}}  fett'"), "{out}");
    assert_eq!(
        texts_str("export default { a: '{{count}}', b: '%s', c: '50% off', d: '---' }"),
        ["50% off"]
    );
    let lit = "export default { a: 'Use \u{27E6}x1\u{27E7} literally' }";
    let out2 = build_str(lit, &[(0, "Nutze \u{27E6}x1\u{27E7} w\u{f6}rtlich")]);
    assert!(
        out2.contains("a: 'Nutze \u{27E6}x1\u{27E7} w\u{f6}rtlich'"),
        "{out2}"
    );
}

// 8 test_refusals (31 shapes)
#[test]
fn refusals_with_a_line_number() {
    let cases: [(&str, &str, usize); 31] = [
        (
            "export default defineMessages({ a: 'A' })",
            "function call",
            1,
        ),
        ("export default {\n  ...base,\n  a: 'A' }", "spread", 2),
        ("export default {\n\n  [key]: 'A' }", "computed key", 3),
        ("export default { a: `Hi ${name}` }", "interpolation", 1),
        ("export default { a() { return 'x' } }", "method", 1),
        ("export default { get a() { return 'x' } }", "getter", 1),
        ("export default { a: () => 'x' }", "arrow function", 1),
        ("export default { a: x => x }", "arrow function", 1),
        ("export default { a: t('A') }", "function call", 1),
        ("export default { a: 'A'.trim() }", "property access", 1),
        ("export default { a: other }", "variable", 1),
        ("export default { other }", "shorthand", 1),
        (
            "import base from './base'\nexport default { a: 'A' }",
            "import",
            1,
        ),
        ("const x = require('./x')", "require", 1),
        ("export default { a: 'A' }\nconsole.log('hi')", "line 2", 2),
        ("export default { a: 'A' } + 1", "end of the statement", 1),
        ("export * from './x'", "export", 1),
        ("export { a } from './x'", "not declared", 1),
        ("export default { a: '\\101' }", "octal", 1),
        ("export default { a: 'A }", "unexpected", 1),
        ("export default { a: `A }", "unterminated template", 1),
        ("/* open\nexport default { a: 'A' }", "unterminated /*", 1),
        ("export default { a: 'A', b: 'B' + c }", "concatenated", 1),
        ("export default { a: new Date() }", "new", 1),
        (
            "export default function () { return { a: 'A' } }",
            "function",
            1,
        ),
        (
            "let x\nexport default { a: 'A' }",
            "without a literal value",
            1,
        ),
        ("export default { a: 'A' };\nwindow.x = 1", "line 2", 2),
        ("export default { a: tag`A` }", "function call", 1),
        ("function f() {}\nexport default {}", "function", 1),
        (
            "export default { a: [ 'A', , 'B' ] }",
            "empty array slot",
            1,
        ),
        ("export default { a: '\\uD83D' }", "lone surrogate", 1),
    ];
    for (src, needle, line) in cases {
        let msg = refused(src, needle);
        assert!(msg.contains(&format!("line {line}:")), "{src:?}: {msg}");
        assert!(msg.contains("never executed"));
    }
    assert!(!JsModule.sniff(b"function main() { console.log('hello') }"));
    assert!(!JsModule.sniff(b"<?xml version=\"1.0\"?><TS version=\"2.1\"></TS>"));
    assert!(JsModule.sniff(ESM.as_bytes()));
}

// 9 test_xml_ts_handoff: LocOS hands an XML .ts to the Qt Linguist filter; Bilingua's filter never reads it as JS
// (the facade picks the Qt filter by sniffing, see WIRING.md).
#[test]
fn xml_ts_is_refused_and_not_sniffed() {
    let msg = refused(QT_TS, "Qt Linguist");
    assert!(msg.contains("XML"));
    assert!(!JsModule.sniff(QT_TS.as_bytes()));
    for bom in [&[0xEF, 0xBB, 0xBF][..], &[]] {
        let mut d = bom.to_vec();
        d.extend_from_slice(b"  \n<TS/>");
        assert!(extract(&d).is_err());
    }
    // UTF-16 XML too
    let mut u16: Vec<u8> = vec![0xFF, 0xFE];
    for c in QT_TS.encode_utf16() {
        u16.extend_from_slice(&c.to_le_bytes());
    }
    assert!(extract(&u16).is_err());
    assert_eq!(texts_str(ESM)[0], "Home"); // a JS .ts stays here
    assert!(JsModule.extensions().contains(&"ts"));
}

