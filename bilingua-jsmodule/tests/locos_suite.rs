// 11 test_printf_regex_linear
#[test]
fn printf_scan_stays_linear_on_a_run_of_zeros() {
    // Counts scanning steps (bilingua_model::work) instead of time: a linear scan does twice the work for twice
    // the zeros, a quadratic one four times.
    let run = |n: usize| {
        let zeros = "0".repeat(n);
        let src = format!("export default {{ a: 'Sale %{zeros}z' }}");
        let (got, work) = bilingua_model::work::count(|| texts_str(&src));
        assert_eq!(got, [format!("Sale %{zeros}z")]);
        work
    };
    let (small, big) = (run(30_000), run(60_000));
    assert!(small >= 30_000, "the scan was not counted: {small}");
    assert!(big * 10 <= small * 25, "{small} steps for 30 000 zeros, {big} for 60 000: more than linear");
    for s in ["Saved %s of %1$d files", "%05.2f%%", "%(name)s left"] {
        assert!(
            texts_str(&format!("export default {{ a: 'Go {s}' }}"))[0].contains('\u{27E6}'),
            "{s}"
        );
    }
}

// 12 test_caps
#[test]
fn caps_nesting_segments_quotes_tokens_and_length() {
    let deep = format!("export default {}'x'{}", "{a:".repeat(40), "}".repeat(40));
    refused(&deep, "nested");
    let lim = { let mut built = bilingua_jsmodule::Limits::default(); built.max_units = 5; built };
    let with = |src: &str| JsModule.extract_with(src.as_bytes(), &ExtractOptions::default(), &lim);
    let many = format!(
        "export default {{{}}}",
        (0..8)
            .map(|i| format!("k{i}: 'Value {i}'"))
            .collect::<Vec<_>>()
            .join(",")
    );
    assert!(matches!(with(&many), Err(Error::Unsupported(m)) if m.contains("segments")));
    let quotes = format!("export default [{}]", "'',".repeat(300));
    assert!(matches!(with(&quotes), Err(Error::Unsupported(m)) if m.contains("strings")));
    let toks = format!("export default {{}}{}", ";".repeat(400));
    assert!(matches!(with(&toks), Err(Error::Unsupported(m)) if m.contains("tokens")));
    let huge = format!("export default {{ a: '{}' }}", "x".repeat(100_001));
    assert!(matches!(extract_str(&huge), Err(Error::Unsupported(m)) if m.contains("longer than")));
}

// 13 test_encodings
#[test]
fn windows_1252_and_utf16_sources_parse_and_export_as_utf8() {
    let src = "export default { a: 'Caf\u{e9} \u{fc}nd' }";
    let cp: Vec<u8> = src.chars().map(|c| c as u32 as u8).collect();
    assert_eq!(texts(&cp), ["Caf\u{e9} \u{fc}nd"]);
    assert_eq!(JsModule.merge(&extract(&cp).unwrap()).unwrap(), cp);
    assert_eq!(
        build_str_bytes(&cp, "Kaffee"),
        "export default { a: 'Kaffee' }"
    );
    match &extract(&cp).unwrap().skeleton {
        Skeleton::Text { encoding, .. } => assert_eq!(encoding, "cp1252"),
        _ => panic!(),
    }
    let mut u16: Vec<u8> = vec![0xFF, 0xFE];
    for c in src.encode_utf16() {
        u16.extend_from_slice(&c.to_le_bytes());
    }
    assert_eq!(texts(&u16), ["Caf\u{e9} \u{fc}nd"]);
    assert_eq!(JsModule.merge(&extract(&u16).unwrap()).unwrap(), u16);
    assert_eq!(build_str_bytes(&u16, "Tee"), "export default { a: 'Tee' }");
}

fn build_str_bytes(data: &[u8], t: &str) -> String {
    String::from_utf8(build(data, &[(0, t)])).unwrap()
}

// 14 test_end_to_end_upload_export (through the Filter API; the upload route is LocOS's)
