// 1 test_registered
#[test]
fn registered_for_every_extension() {
    let f = JsModule;
    for ext in ["js", "mjs", "cjs", "ts", "mts", "cts"] {
        assert!(f.extensions().contains(&ext), "{ext}");
    }
    assert_eq!(f.id(), "js");
}

// 2 test_parse_shapes
#[test]
fn parse_shapes() {
    assert_eq!(
        texts_str(ESM),
        vec![
            "Home",
            "About us",
            // #693: named / numbered placeholders are free-order tokens; tags keep x
            "Hello, \u{27E6}p1\u{27E7}!",
            "no apples | one apple | \u{27E6}p1\u{27E7} apples",
            "See \u{27E6}p1\u{27E7}",
            "Write to us \u{27E6}x1\u{27E7} support",
            "First",
            "Second",
            "Dashed",
        ]
    );
    assert_eq!(
        texts_str(CJS),
        vec![
            "Welcome, \u{27E6}p1\u{27E7}!",
            "You have \u{27E6}p1\u{27E7} unread messages",
            "\u{27E6}p1\u{27E7} Glad you are here.",
            "Click \u{27E6}x1\u{27E7}here\u{27E6}x2\u{27E7} to continue",
            "Saved \u{27E6}x1\u{27E7} of \u{27E6}p2\u{27E7} files",
        ]
    );
    let ts = texts_str(TS);
    assert_eq!(ts[..3], ["OK", "Cancel", "Multi-line\ntemplate title"]);
    assert_eq!(ts[3], "\u{27E6}x1\u{27E7}No items\u{27E6}x2\u{27E7}\u{27E6}x3\u{27E7} item\u{27E6}x4\u{27E7}\u{27E6}x5\u{27E7} items\u{27E6}x6\u{27E7}");
    assert_eq!(ts[4], "\u{27E6}x1\u{27E7}She replied\u{27E6}x2\u{27E7}He replied\u{27E6}x3\u{27E7}They replied\u{27E6}x4\u{27E7}");
    assert_eq!(ts[5], "Part one, part two");
    let doc = extract_str(TS).unwrap();
    let shown = |u: &Unit, id: &str| u.codes[id].standalone.clone().unwrap();
    assert_eq!(shown(&doc.units[3], "1"), "{count, plural, =0 {");
    assert_eq!(shown(&doc.units[3], "3"), "#");
    assert_eq!(shown(&doc.units[3], "6"), "}}");
    for other in [
        "export const en = { a: 'A' }, de = { a: 'B' };\nexport { en, de as fallback }",
        "exports.home = { title: 'Title' }",
        "const m = { a: 'A' }\nmodule.exports = m",
        "export default ({ a: 'A' })",
        "const messages = { a: 'A' };\nexport { messages as default };",
        "#!/usr/bin/env node\nexport default { a: 'A' }",
    ] {
        let t = texts_str(other);
        assert!(t[0] == "A" || t[0] == "Title", "{other}");
    }
}

