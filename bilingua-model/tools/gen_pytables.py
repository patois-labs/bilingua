#!/usr/bin/env python3
"""Generates src/pytables.rs: the code point ranges for Python's str.isalpha, str.isalnum and str.isspace.

Run with the Python whose rules the tables must match (Localization OS runs 3.13):

    python tools/gen_pytables.py > src/pytables.rs

The output names the Python and Unicode versions it was made with. Nothing is read except `unicodedata` and
`str` methods, so any Python 3 can run it.
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    print(f"/// {doc}")
    print(f"pub(crate) static {name}: &[(u32, u32)] = &[")
    line = "   "
    for lo, hi in rs:
        item = f" (0x{lo:X}, 0x{hi:X}),"
        if len(line) + len(item) > 118:
            print(line)
            line = "   "
        line += item
    if line.strip():
        print(line)
    print("];")
    print()


def main():
    sys.stdout.reconfigure(newline="\n")
    print("// @generated by tools/gen_pytables.py - do not edit by hand.")
    print(f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
    print("// Code point ranges (inclusive) where the Python str method is true.")
    print()
    emit("ALPHA", "`str.isalpha`: general category L*.", ranges(str.isalpha))
    emit("ALNUM", "`str.isalnum`: `isalpha` or `isdecimal` or `isdigit` or `isnumeric`.", ranges(str.isalnum))
    emit("DECIMAL", "`str.isdecimal`: category Nd (what `\\d` matches in a Python `re` pattern).", ranges(str.isdecimal))
    emit("SPACE", "`str.isspace`: bidirectional class WS, B or S, or category Zs.", ranges(str.isspace))


if __name__ == "__main__":
    main()
