"""Writes src/cldr.rs data: CLDR cardinal and ordinal plural categories per language, from babel (the data
Localization OS reads).

    <LocOS venv python> -B gen_cldr.py ../src/cldr_data.rs

Cardinal rows: every language babel knows (bit set zero=1 one=2 two=4 few=8 many=16 other=32). Ordinal rows: only
languages whose ordinal categories are more than `other`. Read only use of babel.
"""
import sys

import babel
from babel import Locale
from babel.core import get_global
from babel.localedata import locale_identifiers

BIT = {"zero": 1, "one": 2, "two": 4, "few": 8, "many": 16, "other": 32}


def bits(form):
    return sum(BIT[t] for t in set(form.tags) | {"other"})


card, ordn = {}, {}
for ident in sorted(locale_identifiers()):
    if "_" in ident:
        continue
    try:
        loc = Locale.parse(ident)
    except Exception:
        continue
    card[ident] = bits(loc.plural_form)
    o = bits(loc.ordinal_form)
    if o != 32:
        ordn[ident] = o
# Babel's alias rows: the old and ISO 639-2 codes it resolves to a language (`deu`, `iw`, `tl`, `mo`, ...), plus
# `root` and `und`: (code, the language Babel resolves it to, cardinal bits, ordinal bits), ordinal `other` (32) when the language has no ordinal rule.
alias = {}
for ident in sorted(set(get_global("language_aliases")) | {"root", "und"}):
    if "_" in ident or ident in card:
        continue
    try:
        loc = Locale.parse(ident)
    except Exception:
        continue
    alias[ident] = (loc.language, bits(loc.plural_form), bits(loc.ordinal_form))
with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as fh:
    fh.write(f"// Generated by tools/gen_cldr.py from CLDR cardinal and ordinal plural categories via babel {babel.__version__}\n")
    fh.write("// (the data Localization OS uses). Unicode License: see NOTICE. Do not edit. Sorted by code.\n")
    fh.write("// Bit set: zero=1 one=2 two=4 few=8 many=16 other=32.\n\n")
    for name, rows in (("CARDINAL", card), ("ORDINAL", ordn)):
        fh.write(f"pub(crate) const {name}: &[(&str, u8)] = &[\n")
        for k in sorted(rows):
            fh.write(f'    ("{k}", {rows[k]}),\n')
        fh.write("];\n\n")
    fh.write("pub(crate) const BABEL_ALIASES: &[(&str, &str, u8, u8)] = &[\n")
    for k in sorted(alias):
        fh.write(f'    ("{k}", "{alias[k][0]}", {alias[k][1]}, {alias[k][2]}),\n')
    fh.write("];\n")
print(len(card), len(ordn), len(alias))
