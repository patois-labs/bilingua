"""Writes src/plural_data.rs: the CLDR plural and ordinal categories per locale, from babel (the data LocOS uses).

    <LocOS venv python> -B gen_plurals.py ../../src/plural_data.rs

Only locales whose categories are more than just `other` are listed, and a regional locale only when its
categories differ from its language's. Read only use of babel.
"""
import sys

from babel import Locale
from babel.localedata import locale_identifiers

ORDER = ("zero", "one", "two", "few", "many", "other")


def cats(loc, ordinal):
    form = loc.ordinal_form if ordinal else loc.plural_form
    tags = set(form.tags) | {"other"}
    return "".join({"zero": "z", "one": "o", "two": "t", "few": "f", "many": "m", "other": "x"}[c] for c in ORDER if c in tags)


rows = {}
for ident in sorted(locale_identifiers()):
    try:
        loc = Locale.parse(ident)
    except Exception:
        continue
    rows[ident] = (cats(loc, False), cats(loc, True))
out = []
effective = {}
for ident in sorted(rows, key=lambda i: (i.count("_"), i)):
    parent = ident.rsplit("_", 1)[0] if "_" in ident else None
    inherited = effective.get(parent, ("x", "x")) if parent else ("x", "x")
    effective[ident] = rows[ident]
    if rows[ident] != inherited:
        out.append((ident, *rows[ident]))
out.sort()
with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as fh:
    fh.write("//! Generated by tests/tools/gen_plurals.py from babel (CLDR). Do not edit.\n")
    fh.write("//! Letters: z=zero o=one t=two f=few m=many x=other, in CLDR order.\n\n")
    fh.write("/// (locale id, cardinal categories, ordinal categories), sorted by id.\n")
    fh.write("pub const TABLE: &[(&str, &str, &str)] = &[\n")
    for ident, card, ordn in out:
        fh.write(f'    ("{ident}", "{card}", "{ordn}"),\n')
    fh.write("];\n")
print(len(out), "rows")
