"""Writes src/tables.rs: the Unicode facts the LocOS rst filter gets from Python (str.isalnum, isalpha, isdecimal,
isspace, unicodedata.east_asian_width, combining, category), as sorted code point ranges.

Run with the Localization OS venv Python (read only): python gen_tables.py OUT.rs
"""
import sys
import unicodedata as ud


def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def emit(f, name, rs):
    f.write(f"#[rustfmt::skip]\npub static {name}: &[(u32, u32)] = &[\n")
    line = "   "
    for a, b in rs:
        item = f" (0x{a:X}, 0x{b:X}),"
        if len(line) + len(item) > 118:
            f.write(line + "\n")
            line = "   "
        line += item
    f.write(line + "\n];\n\n")


BITS = {"Ps": 1, "Pe": 2, "Pi": 4, "Pf": 8, "Pd": 16, "Po": 32}


def main():
    out = sys.argv[1]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"//! Generated by tests/tools/gen_tables.py from Python's unicodedata {ud.unidata_version}. Do not edit.\n\n")
        emit(f, "ALNUM", ranges(lambda c: c.isalnum()))
        emit(f, "ALPHA", ranges(lambda c: c.isalpha()))
        emit(f, "DECIMAL", ranges(lambda c: c.isdecimal()))
        emit(f, "SPACE", ranges(lambda c: c.isspace()))
        emit(f, "WIDE", ranges(lambda c: ud.east_asian_width(c) in ("W", "F")))
        emit(f, "COMBINING", ranges(lambda c: ud.combining(c) != 0))
        # category mask ranges (only the P* categories the boundary check reads)
        f.write("/// (first, last, mask): Ps=1 Pe=2 Pi=4 Pf=8 Pd=16 Po=32.\n#[rustfmt::skip]\npub static PUNCT: &[(u32, u32, u8)] = &[\n")
        line, cur = "   ", None
        runs = []
        for cp in range(0x110000):
            m = BITS.get(ud.category(chr(cp)), 0) if not 0xD800 <= cp <= 0xDFFF else 0
            if m and cur and cur[2] == m and cur[1] == cp - 1:
                cur[1] = cp
            elif m:
                cur = [cp, cp, m]
                runs.append(cur)
        for a, b, m in runs:
            item = f" (0x{a:X}, 0x{b:X}, {m}),"
            if len(line) + len(item) > 118:
                f.write(line + "\n")
                line = "   "
            line += item
        f.write(line + "\n];\n")


main()
