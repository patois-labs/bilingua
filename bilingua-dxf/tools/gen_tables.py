"""Writes src/sbcs.rs and src/printable.rs from Python's own codecs and str.isprintable (the LocOS runtime).

    <LocOS venv python> tools/gen_tables.py

Run from the crate folder; read only use of Python, nothing in LocOS is touched.
"""

import sys

# (name in this crate, Python codec). The names are Python's, as LocOS spells them.
PAGES = [
    "cp874", "cp1250", "cp1251", "cp1252", "cp1253", "cp1254", "cp1255", "cp1256", "cp1257", "cp1258",
    "cp437", "cp850", "cp852", "cp855", "cp857", "cp860", "cp861", "cp863", "cp864", "cp865", "cp866", "cp869",
]
UNDEF = 0xFFFFFFFF


def sbcs() -> str:
    out = [
        f"// @generated by tools/gen_tables.py - do not edit by hand. Python {sys.version.split()[0]}.",
        "// Single-byte code pages exactly as Python's codecs read and write them (LocOS uses these).",
        "// Each table maps all 256 bytes to a code point; UNDEF marks a byte the codec rejects. The extras list the",
        "// code points the codec writes as a byte that decodes to something else (cp864 writes U+0025 as 0x25).",
        "",
        "pub const UNDEF: u32 = 0xFFFF_FFFF;",
        "",
        "pub struct Page {",
        "    pub name: &'static str,",
        "    pub table: [u32; 256],",
        "    pub extras: &'static [(u32, u8)],",
        "}",
        "",
        "pub static PAGES: &[Page] = &[",
    ]
    for name in PAGES:
        table = []
        for b in range(256):
            try:
                s = bytes([b]).decode(name)
                assert len(s) == 1
                table.append(ord(s))
            except UnicodeDecodeError:
                table.append(UNDEF)
        image = {u: b for b, u in enumerate(table) if u != UNDEF}
        extras = []
        for cp in range(0x10000):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            try:
                e = chr(cp).encode(name)
            except UnicodeEncodeError:
                continue
            assert len(e) == 1
            if image.get(cp) != e[0]:
                extras.append((cp, e[0]))
        out.append(f'    Page {{ name: "{name}", table: [')
        for i in range(0, 256, 16):
            row = ", ".join("UNDEF" if v == UNDEF else f"0x{v:04X}" for v in table[i : i + 16])
            out.append(f"        {row},")
        ex = ", ".join(f"(0x{c:04X}, 0x{b:02X})" for c, b in extras)
        out.append(f"    ], extras: &[{ex}] }},")
    out.append("];")
    return "\n".join(out) + "\n"


def printable() -> str:
    ranges = []
    start = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            bad = False  # not a Rust char; leave the gap out
        else:
            bad = not chr(cp).isprintable()
        if bad and start is None:
            start = cp
        elif not bad and start is not None:
            ranges.append((start, cp - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))
    out = [
        f"// @generated by tools/gen_tables.py - do not edit by hand. Python {sys.version.split()[0]}, "
        f"Unicode {__import__('unicodedata').unidata_version}.",
        "// Code point ranges (inclusive) where Python's str.isprintable is false (categories Cc, Cf, Co, Cn, Zl, Zp,",
        "// and Zs except the ASCII space). Surrogates are left out: a Rust char is never one.",
        "",
        "pub(crate) static NOT_PRINTABLE: &[(u32, u32)] = &[",
    ]
    row = []
    for a, b in ranges:
        row.append(f"(0x{a:X}, 0x{b:X})")
        if len(row) == 8:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("];")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    with open("src/sbcs.rs", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(sbcs())
    with open("src/printable.rs", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(printable())
    print("written")
