"""Writes src/unitab.rs: the Python character classes the LocOS MDX filter uses, as code point ranges.

    python gen_unitab.py OUT.rs

ALNUM = str.isalnum, PUNCT_SYMBOL = unicodedata.category starts with P or S (CommonMark punctuation).
"""

import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    body = ",".join("(0x%X,0x%X)" % r for r in rs)
    return f"/// {doc}\npub(crate) static {name}: &[(u32, u32)] = &[{body}];\n\n"


with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as fh:
    fh.write(f"//! Generated by tests/tools/gen_unitab.py from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n\n")
    fh.write(emit("ALNUM", "Python `str.isalnum`.", ranges(lambda c: c.isalnum())))
    fh.write(emit("PUNCT_SYMBOL", "Unicode general category P* or S*.", ranges(lambda c: unicodedata.category(c)[0] in "PS")))
    fh.write(emit("SPACE", "Python `str.isspace`.", ranges(lambda c: c.isspace())))
