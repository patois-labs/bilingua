"""Generates src/langnames.rs: the English display names Babel gives for locale codes, as Localization OS's
`catkeys_filter.language_name` uses them (`Locale.parse(code.replace("-", "_")).get_display_name("en")`).

Run with the LocOS venv, read only:  C:/Users/brent/code/local-tms/.venv/Scripts/python.exe -I gen_locale_table.py OUT.rs

Two tables: NAMES (canonical locale id -> English name) and ALIASES (a normalised input that Babel resolves to a
different id, for example `zh_TW` -> `zh_Hant_TW`, `iw` -> `he_IL`). An input that is in neither table is one Babel
refuses (the code is then used as it is).
"""
import json
import sys

from babel import Locale, localedata

ids = sorted(localedata.locale_identifiers())
langs = sorted({i.split("_")[0] for i in ids})
terrs = sorted({p for i in ids for p in i.split("_")[1:] if (len(p) == 2 and p.isupper()) or p.isdigit()})
scripts = sorted({p for i in ids for p in i.split("_")[1:] if len(p) == 4 and p.isalpha()})
lang_scripts = sorted({(i.split("_")[0], p) for i in ids for p in i.split("_")[1:] if p in scripts})
# language aliases Babel knows (iw, in, no, ...): ask it
from babel.core import get_global

alias_langs = ["iw", "in", "ji", "jw", "mo", "no", "tl", "sh", "tw", "nb", "nn", "cmn", "yue", "zh", "swc", "prs", "pa", "mol", "sgn"]
try:
    alias_langs = sorted(set(alias_langs) | set(get_global("language_aliases")))
except Exception:
    pass

names = {}
aliases = {}
PRUNE_ONLY = len(sys.argv) > 2 and sys.argv[2] == "--prune"


def probe(key):
    try:
        loc = Locale.parse(key)
    except Exception:
        return
    canon = str(loc).split("@")[0]
    if canon not in names:
        names[canon] = loc.get_display_name("en")
    if names[canon] is None:
        return  # no display name: LocOS falls back to the code itself
    if canon != key:
        aliases[key] = canon


if not PRUNE_ONLY:
    for i in ids:
        probe(i)
    for lang in sorted(set(langs) | set(alias_langs)):
        probe(lang)
        for t in terrs:
            probe(f"{lang}_{t}")
        for s in scripts:
            probe(f"{lang}_{s}")
    for lang, s in lang_scripts:
        for t in terrs:
            probe(f"{lang}_{s}_{t}")
    # territory-less variants and a few likely ones
    for v in ("VALENCIA", "POSIX", "1996"):
        for lang in langs:
            probe(f"{lang}_{v}")

else:
    import re

    txt = open(sys.argv[1], encoding="utf-8").read()
    head, tail = txt.split("pub(crate) static ALIASES")
    for k, v in re.findall(r'\("([^"]+)", (".*?")\),', head):
        names[k] = json.loads(v)
    for k, v in re.findall(r'\("([^"]+)", "([^"]+)"\),', tail):
        aliases[k] = v


def candidates(key):
    """The keys the Rust lookup tries, in order (see `locale.rs`): drop the variant, then the script."""
    parts = key.split("_")
    lang, rest = parts[0], parts[1:]
    script = next((p for p in rest if len(p) == 4 and p.isalpha()), None)
    terr = next((p for p in rest if (len(p) == 2 and p.isalpha() and p.isupper()) or (len(p) == 3 and p.isdigit())), None)
    variant = next((p for p in rest if p not in (script, terr)), None)

    def j(*xs):
        return "_".join(x for x in xs if x)

    out = [key, j(lang, script, terr), j(lang, terr), j(lang, script), lang]
    if terr:
        out = [key, j(lang, script, terr), j(lang, terr)]
    return list(dict.fromkeys(out))


def resolve(key, al):
    for c in candidates(key):
        canon = al.get(c, c)
        if canon in names and names[canon] is not None:
            return canon
    return None


def prune():
    # a legacy language alias (ISO 639-2 `eng`, `chi`) with a script is not worth a table row: Babel's answer is
    # the plain language, the code is used as it is here
    for k in sorted(aliases):
        parts = k.split("_")
        if parts[0] not in langs and any(len(x) == 4 and x.isalpha() for x in parts[1:]):
            del aliases[k]
    for k in sorted(aliases):
        canon = aliases.pop(k)
        # the alias is needed when, without it, the key would resolve to something else (or nothing)
        if resolve(k, aliases) != canon:
            aliases[k] = canon


import json

prune()
out = ["// Generated by tests/tools/gen_locale_table.py from Babel (the table Localization OS reads). Do not edit.\n",
       "pub(crate) static NAMES: &[(&str, &str)] = &[\n"]
for k in sorted(k for k in names if names[k] is not None):
    out.append(f"    ({json.dumps(k)}, {json.dumps(names[k].lower(), ensure_ascii=False)}),\n")
out.append("];\n\npub(crate) static ALIASES: &[(&str, &str)] = &[\n")
for k in sorted(aliases):
    out.append(f"    ({json.dumps(k)}, {json.dumps(aliases[k])}),\n")
out.append("];\n")
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("".join(out))
print(len(names), len(aliases))
