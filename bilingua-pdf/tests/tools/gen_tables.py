"""Generates `src/tables.rs` (data only) from:

- PDFium (BSD-3-Clause, chromium/8076): `cpdf_fontencoding.cpp` (encoding glyph names and code tables),
  `fx_ucddata.inc` (bidi classes, mirror indexes), `fx_unicode.cpp` (mirror table),
  `unicodenormalizationdata.cpp` (the decomposition PDFium applies to RTL text and ligatures);
- the 391 CFF standard strings (Adobe Technical Note 5176, appendix A; list as in fontTools, MIT), a file of one
  name per line given as the fourth argument;
- Adobe's glyph list (`glyphlist.txt`, BSD-3-Clause) and the core 14 AFM files (Adobe's AFM notice), as shipped in
  the PDFBox 3.0.3 jar resources.

    python gen_tables.py PDFIUM_SRC_DIR PDFBOX_RESOURCES_DIR OUT.rs CFF_STD_STRINGS.txt
"""

import os
import re
import sys

SRC, RES, OUT, CFFSTD = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]


def read(p):
    with open(p, encoding="latin-1") as f:
        return f.read()


def c_array(text, name):
    m = re.search(r"\b" + re.escape(name) + r"(?:\[[^\]]*\])?\s*=\s*\{\{?(.*?)\}\}?;", text, re.S)
    if not m:
        raise SystemExit("missing " + name)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [t.strip().strip("{}").strip() for t in body.split(",") if t.strip().strip("{}").strip()]


enc = read(os.path.join(SRC, "cpdf_fontencoding.cpp"))
# Name tables (the arrays of const char*) in file order, and the code tables.
NAME_TABLES = {
    "STANDARD": "kStandardEncodingNames", "WINANSI": "kAdobeWinAnsiEncodingNames", "MACROMAN": "kMacRomanEncodingNames",
    "MACEXPERT": "kMacExpertEncodingNames", "PDFDOC": "kPDFDocEncodingNames", "SYMBOL": "kAdobeSymbolEncodingNames",
    "ZAPF": "kZapfEncodingNames",
}
CODE_TABLES = {
    "STANDARD": "kStandardEncoding", "WINANSI": "kAdobeWinAnsiEncoding", "MACROMAN": "kMacRomanEncoding",
    "MACEXPERT": "kMacExpertEncoding", "PDFDOC": "kPDFDocEncoding", "SYMBOL": "kAdobeSymbolEncoding",
    "ZAPF": "kZapfEncoding", "MSSYMBOL": "kMSSymbolEncoding",
}

out = ["// @generated by tests/tools/gen_tables.py: do not edit.",
       "//",
       "// Data from PDFium (Copyright 2014 The PDFium Authors, BSD-3-Clause; original code copyright 2014 Foxit",
       "// Software Inc.), Adobe's glyph list (Copyright 1997-2010 Adobe Systems Incorporated, BSD-3-Clause) and metrics",
       "// derived from Adobe's core 14 AFM files. The AFM notice, which travels with that data:",
       "// \"This file and the 14 PostScript(R) AFM files it accompanies may be used, copied, and distributed for any",
       "// purpose and without charge, with or without modification, provided that all copyright notices are retained;",
       "// that the AFM files are not distributed without this file; that all modifications to this file or any of the",
       "// AFM files are prominently noted in the modified file(s); and that this paragraph is not modified. Adobe",
       "// Systems has no responsibility or obligation to support the use of the AFM files.\"",
       "// Modification note: only the advance width and bounding box of each named glyph are kept, as numbers.",
       "#![allow(clippy::all, dead_code)]",
       ""]

for key, cname in NAME_TABLES.items():
    items = c_array(enc, cname)
    first = 24 if key == "PDFDOC" else 32
    vals = ["None" if t == "nullptr" else "Some(%s)" % t for t in items]
    out.append(f"pub const {key}_NAMES_FIRST: usize = {first};")
    out.append(f"pub static {key}_NAMES: [Option<&str>; {len(vals)}] = [" + ", ".join(vals) + "];")
dec = read(os.path.join(SRC, "fpdf_parser_decode.cpp"))
for key, cname in CODE_TABLES.items():
    items = c_array(dec if key == "PDFDOC" else enc, cname)
    assert len(items) == 256, (key, len(items))
    out.append(f"pub static {key}_CODES: [u16; 256] = [" + ", ".join(items) + "];")

# Adobe glyph list: name -> first code point (BMP only, as PDFium keeps 16-bit glyph-list values).
agl = {}
for line in read(os.path.join(RES, "glyphlist", "glyphlist.txt")).splitlines():
    if not line or line.startswith("#"):
        continue
    name, codes = line.split(";")
    cps = codes.split()
    agl.setdefault(name, int(cps[0], 16))
items = sorted(agl.items())
out.append(f"pub static AGL: [(&str, u16); {len(items)}] = [" + ", ".join(f'("{n}", 0x{c:04X})' for n, c in items) + "];")

# Core 14 metrics: per font, sorted (glyph name, width, llx, lly, urx, ury); plus the font bbox, ascender, descender.
fonts = ["Courier", "Courier-Bold", "Courier-BoldOblique", "Courier-Oblique", "Helvetica", "Helvetica-Bold",
         "Helvetica-BoldOblique", "Helvetica-Oblique", "Times-Roman", "Times-Bold", "Times-BoldItalic", "Times-Italic",
         "Symbol", "ZapfDingbats"]
out.append("pub struct Afm { pub name: &'static str, pub bbox: [i16; 4], pub ascent: i16, pub descent: i16, "
           "pub glyphs: &'static [(&'static str, u16, [i16; 4])], pub by_code: &'static [(u8, u16, [i16; 4])] }")
afm_names = []
for font in fonts:
    t = read(os.path.join(RES, "afm", font + ".afm"))
    bbox = [int(x) for x in re.search(r"^FontBBox (.*)$", t, re.M).group(1).split()]
    asc = re.search(r"^Ascender (-?\d+)", t, re.M)
    desc = re.search(r"^Descender (-?\d+)", t, re.M)
    asc = int(asc.group(1)) if asc else bbox[3]
    desc = int(desc.group(1)) if desc else bbox[1]
    glyphs = {}
    codes = []
    for m in re.finditer(r"^C (-?\d+) ; WX (\d+) ; N (\S+) ; B (-?\d+) (-?\d+) (-?\d+) (-?\d+) ;", t, re.M):
        code, wx, name = int(m.group(1)), int(m.group(2)), m.group(3)
        b = [int(m.group(i)) for i in range(4, 8)]
        glyphs[name] = (wx, b)
        if 0 <= code < 256:
            codes.append((code, wx, b))
    ident = re.sub(r"\W", "_", font).upper()
    g = ", ".join(f'("{n}", {w}, [{b[0]}, {b[1]}, {b[2]}, {b[3]}])' for n, (w, b) in sorted(glyphs.items()))
    c = ", ".join(f"({code}, {w}, [{b[0]}, {b[1]}, {b[2]}, {b[3]}])" for code, w, b in sorted(codes))
    out.append(f"static {ident}_G: [(&str, u16, [i16; 4]); {len(glyphs)}] = [{g}];")
    out.append(f"static {ident}_C: [(u8, u16, [i16; 4]); {len(codes)}] = [{c}];")
    out.append(f'pub static {ident}: Afm = Afm {{ name: "{font}", bbox: [{bbox[0]}, {bbox[1]}, {bbox[2]}, {bbox[3]}], '
               f"ascent: {asc}, descent: {desc}, glyphs: &{ident}_G, by_code: &{ident}_C }};")
    afm_names.append(ident)
out.append(f"pub static CORE14: [&Afm; {len(afm_names)}] = [" + ", ".join("&" + n for n in afm_names) + "];")

# Bidi direction runs over the BMP: 0 neutral, 1 left, 2 left-weak, 3 right (PDFium's CFX_BidiChar mapping).
ucd = read(os.path.join(SRC, "fx_ucddata.inc"))
props = re.findall(r"CHARPROP____\((0x[0-9a-f]+)u, (\w+), (\w+), (\w+)\)", ucd)
assert len(props) == 65536, len(props)
DIR = {"kL": 1, "kAN": 2, "kEN": 2, "kNSM": 2, "kCS": 2, "kES": 2, "kET": 2, "kBN": 2, "kR": 3, "kAL": 3}
runs = []
last = None
for cp, (mirror, _ct, bd, _bt) in enumerate(props):
    d = DIR.get(bd, 0)
    if d != last:
        runs.append((cp, d))
        last = d
out.append(f"pub static BIDI_RUNS: [(u16, u8); {len(runs)}] = [" + ", ".join(f"(0x{a:04X}, {d})" for a, d in runs) + "];")
uni = read(os.path.join(SRC, "fx_unicode.cpp"))
mtab = [int(x, 16) for x in c_array(uni, "kFXTextLayoutBidiMirror")]
mirrors = []
for cp, (mirror, _ct, _bd, _bt) in enumerate(props):
    idx = int(mirror, 16)
    if idx != 0x1FF:
        mirrors.append((cp, mtab[idx]))
out.append(f"pub static MIRROR: [(u16, u16); {len(mirrors)}] = [" + ", ".join(f"(0x{a:04X}, 0x{b:04X})" for a, b in mirrors) + "];")

# Normalization: char -> replacement sequence, only the chars PDFium maps.
norm = read(os.path.join(SRC, "unicodenormalizationdata.cpp"))
main = [int(x, 16) for x in c_array(norm, "kUnicodeDataNormalization")]
m1 = [int(x, 16) for x in c_array(norm, "kUnicodeDataNormalizationMap1")]
maps = {2: [int(x, 16) for x in c_array(norm, "kUnicodeDataNormalizationMap2")],
        3: [int(x, 16) for x in c_array(norm, "kUnicodeDataNormalizationMap3")],
        4: [int(x, 16) for x in c_array(norm, "kUnicodeDataNormalizationMap4")]}
assert len(main) == 65536
entries = []
for cp, f in enumerate(main):
    if not f:
        continue
    if f >= 0x8000:
        seq = [m1[f - 0x8000]]
    else:
        idx, n = f & 0x0FFF, f >> 12
        arr = maps[n][idx:]
        if n == 4:
            n, arr = arr[0], arr[1:]
        seq = arr[:n]
    entries.append((cp, seq))
out.append(f"pub static NORMALIZE: [(u16, &[u16]); {len(entries)}] = [" +
           ", ".join(f"(0x{a:04X}, &[{', '.join('0x%04X' % s for s in seq)}])" for a, seq in entries) + "];")

std = [n for n in read(CFFSTD).splitlines() if n]
assert len(std) == 391, len(std)
out.append(f"pub static CFF_STD_STRINGS: [&str; {len(std)}] = [" + ", ".join(f'"{n}"' for n in std) + "];")

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(out) + "\n")
print("tables written", len(agl), "glyph names,", len(runs), "bidi runs,", len(entries), "normalized")
